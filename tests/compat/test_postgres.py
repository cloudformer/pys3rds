# ---- unsupported by design: PostgreSQL runs these, s3rds refuses them with NotSupportedError ----

@pytest.mark.unsupported("row locks need a real server; s3rds has one writer and no sessions")
def test_select_for_update_refused(pg_pair):
    """Unsupported | SELECT ... FOR UPDATE | row locks need a real server"""
    pg_pair([(T, []), (USERS, [])])
    pg_pair.unsupported("SELECT * FROM t FOR UPDATE")


@pytest.mark.unsupported("server-side code; use the application")
def test_function_refused(pg_pair):
    """Unsupported | CREATE FUNCTION / triggers | server-side code; use the application"""
    pg_pair.unsupported("CREATE OR REPLACE FUNCTION s3rds_f() RETURNS integer AS 'SELECT 1' LANGUAGE sql")
    pg_pair.both("DROP FUNCTION IF EXISTS s3rds_f()")


@pytest.mark.unsupported("no session between requests")
def test_listen_refused(pg_pair):
    """Unsupported | LISTEN / NOTIFY | no session between requests"""
    pg_pair.unsupported("LISTEN s3rds_channel")


@pytest.mark.unsupported("SERIAL / IDENTITY primary keys instead")
def test_sequence_refused(pg_pair):
    """Unsupported | CREATE SEQUENCE / nextval | SERIAL primary keys instead"""
    pg_pair.unsupported("CREATE SEQUENCE IF NOT EXISTS s3rds_seq")
    pg_pair.both("DROP SEQUENCE IF EXISTS s3rds_seq")
